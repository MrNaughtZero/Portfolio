export const getProjectList = () => {
	const allProjects = Object.values(projects).map((project) => ({
		slug: project.slug,
		title: project.title.split("\n")[0],
		description: project.description,
		tags: project.tags || [],
		image: project.image || project.heroImage,
		is_featured: project.is_featured || false,
	}));

	const featured = allProjects.filter((project) => project.is_featured);
	const nonFeatured = allProjects.filter((project) => !project.is_featured);

	return [...featured, ...nonFeatured.reverse()];
};
